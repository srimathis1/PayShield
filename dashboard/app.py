import streamlit as st
import pandas as pd

st.set_page_config(
    page_title="PayShield | Transaction Intelligence",
    page_icon="🛡️",
    layout="wide"
)

st.markdown("""
<style>
.stApp { background-color: #0b1120; color: #e2e8f0; }
[data-testid="stMetric"] {
    background: #151f33;
    padding: 18px;
    border: 1px solid #263750;
    border-radius: 12px;
}
h1, h2, h3 { color: #7dd3fc; }
</style>
""", unsafe_allow_html=True)

st.title("🛡️ PayShield")
st.caption("FINANCIAL TRANSACTION INTELLIGENCE | SPARK DATA ENGINEERING")

st.info(
    "Portfolio dashboard using summary metrics from the PaySim "
    "simulated transaction dataset. This is not a live banking system "
    "or a production fraud detector."
)

page = st.sidebar.radio(
    "NAVIGATION",
    ["Overview", "Fraud Analysis", "Pipeline Performance", "AWS Architecture"]
)

if page == "Overview":
    st.header("Transaction Overview")

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Transactions", "6.36 million")
    c2.metric("Fraud-labelled", "8,213")
    c3.metric("Non-fraud-labelled", "6,354,407")
    c4.metric("Flagged by dataset", "16")

    st.subheader("Transaction Volume by Type")

    transaction_types = pd.DataFrame({
        "Transaction Type": [
            "CASH_OUT", "PAYMENT", "CASH_IN", "TRANSFER", "DEBIT"
        ],
        "Transactions": [
            2237500, 2151495, 1399284, 532909, 41432
        ]
    }).set_index("Transaction Type")

    st.bar_chart(transaction_types)

    st.caption(
        "Dataset: PaySim simulated financial transactions. "
        "Counts are from the local dataset analysis."
    )

elif page == "Fraud Analysis":
    st.header("Fraud-Label Analysis")

    fraud_data = pd.DataFrame({
        "Transaction Type": ["TRANSFER", "CASH_OUT"],
        "Fraud-labelled": [4097, 4116],
        "Total Transactions": [532909, 2237500]
    })

    fraud_data["Labelled Rate (%)"] = (
        fraud_data["Fraud-labelled"]
        / fraud_data["Total Transactions"] * 100
    )

    st.dataframe(
        fraud_data.style.format({"Labelled Rate (%)": "{:.3f}%"}),
        use_container_width=True,
        hide_index=True
    )

    st.bar_chart(
        fraud_data.set_index("Transaction Type")[["Fraud-labelled"]]
    )

    st.warning(
        "These are dataset labels, not predictions generated by a trained "
        "machine-learning model. The labelled rate is not a real-world "
        "bank fraud rate."
    )

elif page == "Pipeline Performance":
    st.header("Storage Benchmark")

    st.write(
        "Reported local benchmark comparing CSV and Parquet reads. "
        "This represents one run, not a controlled performance study."
    )

    c1, c2 = st.columns(2)
    c1.metric("CSV size", "470.67 MB")
    c2.metric("Parquet size", "364.49 MB")

    c3, c4 = st.columns(2)
    c3.metric("CSV read and count", "18.44 seconds")
    c4.metric("Parquet read and count", "1.20 seconds")

    st.subheader("Storage Size Comparison")
    st.bar_chart(pd.DataFrame({
        "Format": ["CSV", "Parquet"],
        "Size (MB)": [470.67, 364.49]
    }).set_index("Format"))

    st.success("Reported storage reduction: 22.56%")

    st.markdown("""
    **Engineering concepts demonstrated**
    - CSV versus columnar Parquet storage
    - Spark SQL aggregation
    - Column pruning and predicate pushdown
    - Data validation and pipeline testing
    - Shuffle partition tuning
    """)

elif page == "AWS Architecture":
    st.header("Proposed AWS Architecture")

    steps = [
        ("01", "Amazon S3", "Store raw transaction files"),
        ("02", "AWS Glue / Apache Spark", "Validate, transform and process data"),
        ("03", "Amazon S3 - Curated Zone", "Store processed Parquet data"),
        ("04", "Amazon Athena", "Query curated data using SQL"),
        ("05", "Amazon CloudWatch", "Monitor pipeline logs and failures"),
        ("06", "PayShield Dashboard", "Present transaction analytics")
    ]

    for number, service, description in steps:
        with st.container(border=True):
            st.markdown(f"### {number} · {service}")
            st.write(description)

    st.warning(
        "This is a proposed architecture. These AWS services have not "
        "yet been connected or deployed in this project."
    )

st.divider()
st.caption("PayShield | Built with Python, Apache Spark, PySpark and Streamlit")
